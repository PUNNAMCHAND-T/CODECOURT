"""Pydantic schemas for code review findings.

Validates LLM-generated findings, internal database persistence payloads,
and API responses with strict typing on category, severity, and line ranges.
"""

from datetime import datetime
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field, model_validator

from backend.app.schemas.feedback import FeedbackResponse

# Allowed categories and severities per PROJECT.md §5
FindingCategory = Literal["security", "performance", "maintainability", "correctness"]
FindingSeverity = Literal["low", "medium", "high", "critical"]
FindingStatus = Literal["active", "merged", "dropped"]


class RawAgentFinding(BaseModel):
    """Raw finding emitted by an LLM reviewer agent before validation."""

    model_config = ConfigDict(extra="ignore")

    category: FindingCategory = Field(
        ...,
        description="Issue category: security, performance, maintainability, or correctness",
    )
    severity: FindingSeverity = Field(
        ...,
        description="Issue severity: low, medium, high, or critical",
    )
    file: str = Field(
        ...,
        min_length=1,
        description="Relative file path where the issue occurs",
    )
    line_start: int = Field(
        ...,
        ge=1,
        description="1-indexed starting line number of the issue in the new file",
    )
    line_end: int = Field(
        ...,
        ge=1,
        description="1-indexed ending line number of the issue in the new file",
    )
    title: str = Field(
        ...,
        min_length=3,
        max_length=255,
        description="Concise, actionable issue title",
    )
    explanation: str = Field(
        ...,
        min_length=10,
        description="Detailed technical reasoning explaining why this is an issue",
    )
    evidence: str = Field(
        ...,
        min_length=1,
        description="Quoted code from the diff or tool result confirming the issue",
    )
    suggested_fix: str | None = Field(
        default=None,
        description="Concrete suggestion or replacement code snippet to resolve the issue",
    )
    confidence: float = Field(
        ...,
        ge=0.0,
        le=1.0,
        description="Investigation score from 0.0 to 1.0 (heuristic, not calibrated probability)",
    )

    @model_validator(mode="after")
    def validate_line_range(self) -> "RawAgentFinding":
        """Ensure line_end is greater than or equal to line_start."""
        if self.line_end < self.line_start:
            raise ValueError(
                f"line_end ({self.line_end}) cannot be less than line_start ({self.line_start})"
            )
        return self


class AgentReviewOutput(BaseModel):
    """Schema for validating structured JSON output generated by LLM reviewers."""

    model_config = ConfigDict(extra="ignore")

    summary: str = Field(
        default="",
        description="High-level markdown summary of the review findings",
    )
    findings: list[RawAgentFinding] = Field(
        default_factory=list,
        description="List of detected code findings",
    )


class FindingCreate(RawAgentFinding):
    """Payload for persisting a validated finding in the database."""

    review_id: int = Field(..., ge=1)
    agent: str = Field(
        ...,
        min_length=1,
        description="Identifier of the emitting agent (e.g. 'single_agent', 'security', 'judge')",
    )
    status: FindingStatus = Field(default="active")
    merged_from: list[str] | None = Field(
        default=None,
        description="Original finding IDs that were synthesized into this finding by the judge",
    )
    decision_reason: str | None = Field(
        default=None,
        description="Judge rationale for keeping or merging this finding",
    )
    drop_reason: str | None = Field(
        default=None,
        description="Judge or validator rationale if the finding was dropped",
    )


class FindingResponse(BaseModel):
    """Standardized API response representing a single finding."""

    model_config = ConfigDict(from_attributes=True)

    id: int
    review_id: int
    agent: str
    category: FindingCategory
    severity: FindingSeverity
    file: str
    line_start: int
    line_end: int
    title: str
    explanation: str
    evidence: str
    suggested_fix: str | None
    confidence: float
    status: FindingStatus
    merged_from: list[str] | None
    decision_reason: str | None
    drop_reason: str | None
    created_at: datetime
    feedback: "FeedbackResponse | None" = Field(
        default=None,
        description="Optional human feedback (accepted or dismissed)",
    )


class ValidatedFinding(BaseModel):
    """Result of deterministic validation on an individual finding."""

    model_config = ConfigDict(extra="ignore")

    finding: RawAgentFinding
    is_valid: bool
    repaired: bool = False
    drop_reason: str | None = None
    repair_details: list[str] = Field(default_factory=list)


class FindingValidationResult(BaseModel):
    """Aggregate result of deterministic finding validation for a review."""

    model_config = ConfigDict(extra="ignore")

    total_evaluated: int = 0
    accepted: list[RawAgentFinding] = Field(default_factory=list)
    dropped: list[ValidatedFinding] = Field(default_factory=list)
    repaired_count: int = 0
