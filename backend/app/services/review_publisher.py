"""GitHub pull request review publisher service.

Formats validated code review findings into structured GitHub PR reviews
with top-level summaries and anchored multi-line inline comments.
"""

import logging
from collections.abc import Sequence
from typing import Literal

from backend.app.schemas.finding import RawAgentFinding
from backend.app.schemas.github import (
    GitHubPublishedReview,
    GitHubReviewComment,
    GitHubReviewPublishPayload,
)
from backend.app.services.github_client import GitHubAuthenticationError, GitHubClient

logger = logging.getLogger(__name__)


def format_finding_comment(finding: RawAgentFinding) -> str:
    """Format an individual finding into a structured markdown review comment."""
    severity_icon = {
        "critical": "🚨",
        "high": "⚠️",
        "medium": "⚡",
        "low": "💡",
    }.get(finding.severity, "🔍")

    lines = [
        f"### {severity_icon} [{finding.severity.upper()}] {finding.title}",
        "",
        f"**Category:** `{finding.category}` | **Confidence:** `{finding.confidence:.2f}`",
        "",
        finding.explanation,
        "",
        "#### 🔍 Evidence",
        "```",
        finding.evidence,
        "```",
    ]

    if finding.suggested_fix:
        lines.extend(
            [
                "",
                "#### 💡 Suggested Fix",
                "```suggestion",
                finding.suggested_fix,
                "```",
            ]
        )

    return "\n".join(lines)


def format_review_body(
    summary: str,
    findings: Sequence[RawAgentFinding],
    model: str | None = None,
) -> str:
    """Format top-level review markdown summary with statistics."""
    lines = [
        "## ⚖️ CodeCourt Automated PR Review",
        "",
        "### 📋 Executive Summary",
        summary.strip() if summary.strip() else "Automated code review completed.",
        "",
    ]

    if not findings:
        lines.extend(
            [
                "> ✅ **No issues identified.** All analyzed code changes satisfy security, performance, and maintainability criteria.",
                "",
            ]
        )
    else:
        # Findings distribution count
        counts_by_sev: dict[str, int] = {}
        counts_by_cat: dict[str, int] = {}
        for f in findings:
            counts_by_sev[f.severity] = counts_by_sev.get(f.severity, 0) + 1
            counts_by_cat[f.category] = counts_by_cat.get(f.category, 0) + 1

        sev_order = ["critical", "high", "medium", "low"]
        sev_parts = [
            f"**{s.capitalize()}:** {counts_by_sev[s]}" for s in sev_order if s in counts_by_sev
        ]

        lines.extend(
            [
                "### 📊 Findings Overview",
                f"Total Issues: **{len(findings)}** | " + " | ".join(sev_parts),
                "",
                "| Category | Count |",
                "| :--- | :--- |",
            ]
        )
        for cat in sorted(counts_by_cat.keys()):
            lines.append(f"| `{cat}` | {counts_by_cat[cat]} |")
        lines.append("")

    lines.extend(
        [
            "---",
            f"*Generated by CodeCourt review pipeline{f' using {model}' if model else ''}*",
        ]
    )
    return "\n".join(lines)


def determine_review_event(
    findings: Sequence[RawAgentFinding],
) -> Literal["COMMENT", "APPROVE", "REQUEST_CHANGES"]:
    """Determine the GitHub review action based on finding severity.

    - REQUEST_CHANGES if any critical or high severity finding exists.
    - APPROVE if zero findings were detected.
    - COMMENT for medium or low findings.
    """
    if not findings:
        return "APPROVE"

    has_severe = any(f.severity in {"critical", "high"} for f in findings)
    if has_severe:
        return "REQUEST_CHANGES"

    return "COMMENT"


def build_review_payload(
    commit_id: str,
    summary: str,
    findings: Sequence[RawAgentFinding],
    model: str | None = None,
) -> GitHubReviewPublishPayload:
    """Build the full review payload with inline comments for the GitHub API."""
    comments: list[GitHubReviewComment] = []

    for finding in findings:
        comment_body = format_finding_comment(finding)
        # GitHub review comment API:
        # If multi-line, line is the end line and start_line is the start line.
        # If single-line, line is the line and start_line should be None.
        if finding.line_start < finding.line_end:
            comments.append(
                GitHubReviewComment(
                    path=finding.file,
                    body=comment_body,
                    line=finding.line_end,
                    start_line=finding.line_start,
                    side="RIGHT",
                )
            )
        else:
            comments.append(
                GitHubReviewComment(
                    path=finding.file,
                    body=comment_body,
                    line=finding.line_end,
                    start_line=None,
                    side="RIGHT",
                )
            )

    body = format_review_body(summary, findings, model=model)
    event = determine_review_event(findings)

    return GitHubReviewPublishPayload(
        commit_id=commit_id,
        body=body,
        event=event,
        comments=comments,
    )


async def publish_pull_request_review(
    github_client: GitHubClient,
    owner: str,
    repo: str,
    pull_number: int,
    payload: GitHubReviewPublishPayload,
    dry_run: bool = False,
) -> GitHubPublishedReview:
    """Publish a review payload to the GitHub PR.

    In dry_run mode, formats payload and logs without performing network writes.
    In real mode, executes authenticated POST to GitHub REST API.
    """
    if dry_run:
        logger.info(
            "Dry-run: review for %s/%s#%d prepared (%d inline comments, event=%s)",
            owner,
            repo,
            pull_number,
            len(payload.comments),
            payload.event,
        )
        return GitHubPublishedReview(
            id=None,
            html_url=None,
            state=payload.event,
            comment_count=len(payload.comments),
            is_dry_run=True,
        )

    if not github_client.token:
        raise GitHubAuthenticationError(
            "GitHub token is required to publish review. Configure GITHUB_TOKEN or enable dry_run."
        )

    comments_data = [c.model_dump(exclude_none=True) for c in payload.comments]

    response_data = await github_client.create_pull_request_review(
        owner=owner,
        repo=repo,
        pull_number=pull_number,
        commit_id=payload.commit_id,
        body=payload.body,
        event=payload.event,
        comments=comments_data,
    )

    review_id = response_data.get("id")
    html_url = response_data.get("html_url")
    state = response_data.get("state", payload.event)

    logger.info(
        "Published GitHub review #%s for %s/%s#%d (state=%s, comments=%d)",
        review_id,
        owner,
        repo,
        pull_number,
        state,
        len(payload.comments),
    )

    return GitHubPublishedReview(
        id=review_id,
        html_url=html_url,
        state=state,
        comment_count=len(payload.comments),
        is_dry_run=False,
    )
